### Operadores aritméticos ###

print(5 + 3) #Suma
print(5 - 3) #Resta
print(5 * 3) #Multiplicación
print(5 / 3) #División
print(5 % 3) #Módulo es el resto de la división
print(5 ** 3) #Potencia
print(5 // 3) #División entera es el cociente de la división

print("Hola " + "Mundo") #Concatenación
print("Hola " * 3) #Repetición
print("Hola " + str(3)) #Concatenación de texto con número

### Operadores de comparación ###

print(5 > 3) #Mayor que
print(5 < 3) #Menor que
print(5 >= 3) #Mayor o igual que
print(5 <= 3) #Menor o igual que
print(5 == 3) #Igual que
print(5 != 3) #Diferente que

print("Hola" == "Python") #Igual que
print("Hola" != "Python") #Diferente que
print("Hola" > "Python") #Mayor que
print("Hola" < "Python") #Menor que
print(len("Holass") == len("Python")) #Comparación de longitud de cadenas
      

### Operadores lógicos ###

print (3 > 4 and "Hola" > "Python") # and
print (3 > 4 or "Hola" > "Python") # or
